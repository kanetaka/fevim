"""Generate src/editor/options_table.rs from Vim's optiondefs.h / option.h.

Usage: python tools/gen_options.py ../vim/src
"""
import os
import re
import sys

src = sys.argv[1]
defs = open(os.path.join(src, "optiondefs.h"), encoding="utf-8", errors="replace").read()
opth = open(os.path.join(src, "option.h"), encoding="utf-8", errors="replace").read()

scope = {}
for m in re.finditer(r"#\s*define\s+(PV_\w+)\s+(.*)", defs + opth):
    v = m.group(2)
    scope[m.group(1)] = "Win" if "OPT_WIN" in v else ("Buf" if "OPT_BUF" in v else "Global")

start = defs.index("static struct vimoption options[]")
body = defs[start:]
out = []
seen = set()
for m in re.finditer(r'\{"(\w+)"\s*,\s*(?:"(\w+)"|NULL)\s*,\s*(P_\w+)', body):
    name, short, ty = m.group(1), m.group(2) or "", m.group(3)
    if name in seen:
        continue
    seen.add(name)
    rest = body[m.end():m.end() + 600]
    end = rest.find("SCTX_INIT")
    rest = rest[: end if end > 0 else 600]
    pv = re.search(r"\b(PV_\w+)", rest)
    sc = "Global"
    if "VAR_WIN" in rest:
        sc = "Win"
    elif pv and pv.group(1) != "PV_NONE":
        sc = scope.get(pv.group(1), "Buf")
    kind = {"P_BOOL": "Bool", "P_NUM": "Num", "P_STRING": "Str"}[ty]
    flags = body[m.start():m.start() + 400].split("(char_u", 1)[0]
    comma = "true" if ("P_COMMA" in flags or "P_ONECOMMA" in flags) else "false"
    flagl = "true" if "P_FLAGLIST" in flags else "false"
    expand = "true" if "P_EXPAND" in flags else "false"
    out.append((name, short, kind, sc, comma, flagl, expand))

with open("src/editor/options_table.rs", "w", encoding="utf-8", newline="\n") as f:
    f.write("// @generated by tools/gen_options.py from Vim's optiondefs.h. Do not edit.\n")
    f.write("use super::options::{OptDef, OptKind::*, OptScope::*};\n\n")
    f.write("pub static OPTION_DEFS: &[OptDef] = &[\n")
    for name, short, kind, sc, comma, flagl, expand in out:
        f.write(
            "    OptDef { name: \"%s\", short: \"%s\", kind: %s, scope: %s, comma: %s, flaglist: %s, expand: %s },\n"
            % (name, short, kind, sc, comma, flagl, expand)
        )
    f.write("];\n")
print(len(out), "options")
